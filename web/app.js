  /** Count-up on first reveal (skipped for reduced motion). */
  function countUp(scope) {
    var els = $$('.stat-value[data-count]', scope);
    function run(el) {
      var target = parseFloat(el.dataset.count), dec = parseInt(el.dataset.dec || '0', 10);
      if (reducedMotion()) { el.textContent = target.toFixed(dec); return; }
      var start = performance.now(), dur = 1100;
      (function step(now) {
        var p = Math.min(1, (now - start) / dur);
        var eased = 1 - Math.pow(1 - p, 3);
        el.textContent = (target * eased).toFixed(dec);
        if (p < 1) requestAnimationFrame(step);
      })(start);
    }
    if (!window.IntersectionObserver) { els.forEach(run); return; }
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) { if (e.isIntersecting) { run(e.target); io.unobserve(e.target); } });
    }, { threshold: .4 });
    els.forEach(function (el) { io.observe(el); });
  }

